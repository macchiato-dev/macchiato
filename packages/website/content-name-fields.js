// Shared by the outer guest's organization form and the editor guest's
// project form. Neither form needs the other guest in order to name content.
export function mountContentNameFields() {
  const generatedSlugs = new WeakMap();
  const pattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
  const slugSelector = "#project-slug, #organization-slug";

  function slugify(value) {
    const text = String(value || "");
    const normalized = typeof text.normalize === "function" ? text.normalize("NFKD") : text;
    return normalized.replace(/[\u0300-\u036f]/g, "")
      .toLowerCase().replace(/[’']/g, "").replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "").slice(0, 63).replace(/-+$/g, "");
  }

  function validate(slug, touched = true) {
    const error = document.getElementById(slug.getAttribute("aria-describedby"));
    if (!error) return;
    const invalid = slug.value !== "" && !pattern.test(slug.value);
    slug.setCustomValidity(invalid ? error.dataset.message : "");
    slug.setAttribute("aria-invalid", invalid ? "true" : "false");
    error.hidden = !invalid || !touched;
  }

  function onInput(event) {
    const source = event.target.closest?.("[data-slug-source], #project-name, #organization-name");
    if (source) {
      const id = source.dataset.slugSource || (source.id === "project-name"
        ? "project-slug" : source.id === "organization-name" ? "organization-slug" : "");
      const slug = document.getElementById(id);
      if (!slug) return;
      // A pre-existing or manually entered name must not be mistaken for one
      // generated by this handler on the first title edit.
      const previous = generatedSlugs.get(source) ?? "";
      if (slug.value !== "" && slug.value !== previous) return;
      const generated = slugify(source.value);
      generatedSlugs.set(source, generated);
      slug.value = generated;
      validate(slug, false);
      return;
    }
    const slug = event.target.closest?.(slugSelector);
    if (slug) validate(slug);
  }
  function onFocusOut(event) {
    const slug = event.target.closest?.(slugSelector);
    if (slug) validate(slug);
  }
  // These fields already exist when their page/form is mounted. Listening on
  // them avoids forwarding every CodeMirror input event through unrelated
  // name validation, especially during a large native insertion.
  for (const field of document.querySelectorAll(
    `[data-slug-source], #project-name, #organization-name, ${slugSelector}`)) {
    field.addEventListener("input", onInput);
    // Static forms are usable while the guest loads. Adopt an already typed
    // title, but preserve any name the user entered before listeners existed.
    if (field.value) onInput({ target: field });
  }
  for (const field of document.querySelectorAll(slugSelector)) {
    field.addEventListener("focusout", onFocusOut);
  }
}
