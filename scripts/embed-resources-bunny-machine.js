import { gzipSync } from "node:zlib";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generated = join(root, "packages/website/generated");
const output = join(generated, "resources-bunny-machine-assets.ts");

function compressedBase64(path) {
  return gzipSync(readFileSync(path), { level: 9 }).toString("base64");
}

function bytecodeSet(directory) {
  const root = join(generated, directory);
  const manifest = JSON.parse(readFileSync(join(root, "manifest.json"), "utf8"));
  return manifest.chunks.map(name => compressedBase64(join(root, name)));
}

const runtime = compressedBase64(join(generated, "microquickjs-server.wasm"));
const server = bytecodeSet("resources-server-bytecode");
writeFileSync(output, `// Generated by scripts/embed-resources-bunny-machine.js.\n` +
  `export const runtimeGzipBase64 = ${JSON.stringify(runtime)};\n` +
  `export const serverBytecodeGzipBase64 = ${JSON.stringify(server)};\n`);
